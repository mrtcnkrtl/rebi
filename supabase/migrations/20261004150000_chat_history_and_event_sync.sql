-- Web ve mobil aynı veriyi görsün: sohbet geçmişi sunucuda saklanır ve
-- gün içi olaylar istemci kimliğiyle tekrar-güvenli yazılır.

create table if not exists public.chat_history (
  id uuid primary key default gen_random_uuid(),
  -- seq aynı anda yazılan kullanıcı/asistan satırlarını sıralar ve
  -- mobil istemci için artımlı okuma imleci olarak kullanılır.
  seq bigint generated by default as identity,
  user_id uuid not null references auth.users (id) on delete cascade,
  surface text not null default 'general',
  role text not null,
  content text not null,
  concern text,
  created_at timestamptz not null default now(),
  constraint chat_history_role_chk check (role in ('user', 'assistant')),
  constraint chat_history_surface_chk check (surface in ('general', 'concern', 'assessment'))
);

create index if not exists chat_history_user_seq_idx
  on public.chat_history (user_id, seq desc);

alter table public.chat_history enable row level security;

-- Backend service_role RLS'yi bypass eder. Aşağıdakiler doğrudan Supabase
-- istemcisi (kullanıcı JWT'si) için: kendi satırını okur ve silebilir.
-- Yazma yalnızca backend'e aittir; üretilen yanıtın geçmişi istemci tarafından
-- değiştirilemesin diye insert/update politikası tanımlanmaz.
drop policy if exists "Users can view own chat_history" on public.chat_history;
create policy "Users can view own chat_history"
  on public.chat_history for select
  to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Users can delete own chat_history" on public.chat_history;
create policy "Users can delete own chat_history"
  on public.chat_history for delete
  to authenticated
  using (auth.uid() = user_id);

comment on table public.chat_history is
  'Rebi: sohbet geçmişi (backend yazar; web ve mobil aynı geçmişi okur).';

-- Çevrimdışı kuyruktan tekrar gönderilen olay iki kez yazılmasın.
alter table public.daily_events
  add column if not exists client_event_id text;

-- Kısmi değil tam indeks: ON CONFLICT bu indeksi çıkarsayabilsin.
-- client_event_id null olan satırlar unique kısıtı tetiklemez.
create unique index if not exists daily_events_user_client_event_idx
  on public.daily_events (user_id, client_event_id);

comment on column public.daily_events.client_event_id is
  'İstemcinin ürettiği olay kimliği; aynı olayın tekrar yazılmasını engeller.';

create or replace function public.purge_expired_rebi_data()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  n_intro integer := 0;
  n_events integer := 0;
  n_logs integer := 0;
  n_routines integer := 0;
  n_assessments integer := 0;
  n_chat integer := 0;
begin
  delete from public.intro_seen_ips
  where seen_at < now() - interval '180 days';
  get diagnostics n_intro = row_count;

  delete from public.daily_events
  where event_time < now() - interval '400 days';
  get diagnostics n_events = row_count;

  delete from public.daily_logs
  where log_date < current_date - 730;
  get diagnostics n_logs = row_count;

  delete from public.routines
  where is_active is false
    and created_at < now() - interval '730 days';
  get diagnostics n_routines = row_count;

  delete from public.assessments a
  where a.created_at < now() - interval '730 days'
    and not exists (
      select 1
      from public.routines r
      where r.assessment_id = a.id
    );
  get diagnostics n_assessments = row_count;

  delete from public.chat_history
  where created_at < now() - interval '365 days';
  get diagnostics n_chat = row_count;

  return jsonb_build_object(
    'intro_seen_ips', n_intro,
    'daily_events', n_events,
    'daily_logs', n_logs,
    'inactive_routines', n_routines,
    'assessments', n_assessments,
    'chat_history', n_chat
  );
end;
$$;

revoke all on function public.purge_expired_rebi_data() from public;
revoke all on function public.purge_expired_rebi_data() from anon;
revoke all on function public.purge_expired_rebi_data() from authenticated;
grant execute on function public.purge_expired_rebi_data() to service_role;

comment on function public.purge_expired_rebi_data() is
  'Rebi retention: intro 180g, daily events 400g, chat 365g, daily logs and unused historical records 730g.';
